def getConfig():
    """
    Returns configuration for executing McStas simulation as dict.
        
    Use setConfig() for changing the configuration.
    
    Returns:
    ----------
    
    A dict with keys:
    
    WORKPATH: str
        Path where the compiled Mcstas instrument is searched for.
    INSTR: str
         Name of the McStas instrument (no extensions).
    EXE: str
         File name of the compiled McStas instrument executable, 
         INSTR+'.exe'
    OUTPATH: str
        Path where Mcstas saves results (adds mode name as subdirectory).
        This must be a relative path to the WORKPATH directory.
    """
    
    global _MCSTAS_PATH, _MCSTAS_OUT, _MCSTAS_INST
    res = {}
    res['WORKPATH'] = _MCSTAS_PATH
    res['OUTPATH'] = _MCSTAS_OUT
    res['INSTR'] = _MCSTAS_INST
    res['EXE'] = _MCSTAS_INST+'.exe'
    return res
        

def createWorkspace():
    """Check workspace directories and create missing ones.
    
    Copy resource files to the workspace directory and check the setup 
    (files exist).
    """
    # create workspace directories
    config = getConfig()
    dirs = [config['OUTPATH'], config['WORKPATH']]
    for d in dirs:
        if not os.path.isdir(d):
            try:
                print('Creating directory: {}'.format(d))
                os.makedirs(d)
            except Exception as e:
                print('Failed to create directory: {}'.format(d))
                raise Exception(e)

    # copy resource files to workspace
    if 'cmd' in _MCSTAS_ENV:
        files = [_MCSTAS_ENV['cmd']]
        copyResources(config['WORKPATH'], files=files)
        

def setConfig(workpath='', instname='BEER_reference', outpath='out'):
    """Set McStas project configuration.
    
    Create workspace files and directories if needed. 
    
    Must be executed before calling run* functions from this module.
    
    Parameters
    ----------
    workpath : str
        Root project directory with instrument data and output. 
        If not defined, takes a default path in user profile (./beer_optics/mcstas) 
    instname : str
        Name of the McStas instrument to run. Currently only `BEER_reference` 
        is defined in resources.
    outpath : str
        Path where Mcstas saves results (adds mode name as subdirectory).
        If relative, it is assumed to be a child of `workpath`. 
    
    """
    global _MCSTAS_PATH, _MCSTAS_OUT, _MCSTAS_INST
    
    if workpath:
        _MCSTAS_PATH = os.path.normpath(workpath)
    if outpath:
        if os.path.isabs(outpath):  
            _MCSTAS_OUT = os.path.normpath(outpath)
        else:
            _MCSTAS_OUT = os.path.normpath(os.path.join(_MCSTAS_PATH,outpath))
    if instname:
        _MCSTAS_INST = instname



#%% Create instrument file and compile it

def createInstrument(template='', inpath=None, outpath=None, instname='', 
                     **options):
    """Create McStas instrument file from a template.
    
    The created file is saved in the workspace as defined by :func:`setConfig`. 
    
    The template file is searched for in the package resources, 
    unless `inpath` is defined.
    
    Parameters
    ----------
    template : str
        Template name. If empty, use the instrument name (see :func:`setConfig`)
    inpath: str
        path where to search for instrument template. If not defined, use
        package resources.
    outpath : str
        Path where to save the instrument file (must already exist). 
        If None, use the workspace setting.
    instname : str
        Instrument name (without instr extension). If empty, use the name 
        defined by :func:`setConfig`
    """
    config = getConfig()
    
    if not template:
        template = config['INSTR']+'_3x_GPU'
    if not instname:
        instname = config['INSTR']
    else:
        setConfig(instname=instname)
    if outpath is None:
        outpath = config['WORKPATH']
        checkConfig(config)

    BMC.parseTemplate(instname=instname, 
                  template=template,
                  outpath=outpath, 
                  inpath=inpath,
                  **options)


def compileInstrument(mpi=0, verify=True):
    """
    Attempts to compile instrument file specified in config.
    No validation of McStas compiler is done. It is assumed that
    PATH, MCSTAS and MCSTAS_CC environment variables contain valid info
    on McStas installation.
    
    Parameters:
    -----------
    verify:
        If true, verify first that mcstas is configured properly
        by calling verifyMcStas()
    """
    mcstas = getMcStas()
    # get and check environment
    if verify:
        if not verifyMcStas():
            print('Cannot compile instrument file.')
            return
        env = os.environ
    else:
        # Set environment
        # Set and check environment variables
        env = os.environ
        for v in ['MCSTAS','MCSTAS_CC','MCSTAS_CFLAGS']:
            if v in mcstas:
                env[v] = mcstas[v]
    
    # check that there is instr file to compile
    config = getConfig()
    instfile = os.path.join(config['WORKPATH'],config['INSTR']+'.instr')
    if not os.path.isfile(instfile):
        raise Exception('Instrument file is missing: {}'.format(instfile))
    
    # run compiler using the script compile.* from resources
    res = False
    out = None
    scr = os.path.join(config['WORKPATH'],mcstas['cmd'])
    if not os.path.isfile(scr):
        print('Compilation script not found: "{}"'.format(scr))
        return res
    try:
        # remove *.c file
        fc = os.path.join(config['WORKPATH'],config['INSTR']+'.c')
        if os.path.isfile(fc):
            os.remove(fc)
        
        """
        if 'SHELL' in env:
            cmd = [env['SHELL']]
        else:
            cmd = []
        cmd = cmd + [mcstas['cmd'], config['INSTR']]
        """
        
        cmd = ['mcrun','-c']
        if mpi:
            cmd.append('--mpi={}'.format(mpi))
        cmd.append(config['INSTR']+'.instr')
        cmd.append('-n0') # suppress running, just compile
        # join into one command string - lists may not run on Linux ...
        cmd = ' '.join(cmd)
        print('Command: '+cmd)
        print('Compiling ... ',end='')
# for Python >= 3.7 :
#        out = subprocess.run(cmd, capture_output=True, text=True, shell=True, check=True)
# for Python < 3.7 :
        out = subprocess.run(cmd, cwd=config['WORKPATH'], env=env,
                             stdout=subprocess.PIPE, stderr=subprocess.STDOUT, 
                             universal_newlines=True, shell=True, check=True,
                             timeout=1000)
        out.check_returncode()
        print('done.')
        res = True
    except CalledProcessError as e:
        print('failed.')
        msg = 'Can\'t execute {}.\n'.format(cmd)
        msg += 'Return code: {:d}\n'.format(e.returncode)
        if e.stderr: msg += 'stderr:\n'+e.stderr +'\n'
        if e.stdout: msg += 'stdout:\n'+e.stdout +'\n'
        print(msg)
        return res
    except TimeoutExpired as e:
        print('timeout at {} s.'.format(e.timeout))
        return res
    except Exception:
        print('Error while executing {}'.format(cmd))
        traceback.print_exc(file=sys.stdout)
    return res



def runSimulation(mode, n=10000, mpi=0, verbose=1, npulse=0, timeout=600, 
                  outdir=None, quiet=False, **kwargs):
    """
    Run McStas simulation with given parameters. Optinally plot results.
    
    Parameters:
    -----------
    mode: int or str
        BEER reference mode index or ID
    n: int
        Number of neutrons to run
    verbose: int
        `verbose` parameter passed to McStas instrument file
    npulse: int
        `npulse` parameter passed to McStas instrument file
    timeout: int
        imeout in sec for execution
    outdir: str
        McStas output directory, relative to config['OUTPATH'].
        If not provided, mode ID string is used.
    """
    # verify configuration
    if not verifyConfig(verbose=not quiet):
        return

    # check that the executable exists
    exename = verifyInstrument(verbose=not quiet)     
    if not exename:
        return

    # get configuration
    config = getConfig()
    outpath = os.path.normpath(config['OUTPATH'])

    # get mode info
    if isinstance(mode, int):
        modeid = BMOD.modes[mode]['ID']
        imode = mode
    elif isinstance(mode, str):
        modeid = mode
        imode = BMOD.getModeIndex(mode)
    else:
        raise Exception('Wrong mode parameter: '+mode)
    
    # set output directory
    if outdir:
        outname = os.path.join(outpath,outdir)
    else:
        outname = os.path.join(outpath,modeid)
    
    # define -d parameter 
    # for relative outname, we must take it relative to WORKPATH
    # since simulations run in WORKPATH
    if not os.path.isabs(outname):
        respath = os.path.relpath(outname, config['WORKPATH'])
    else:
        respath = outname
        
    # set up command parameters
    sn = '-n{:d}'.format(int(n))
    smode = 'mode={:d}'.format(imode)
    snpls = 'npulse={:d}'.format(npulse)
    sv = 'verbose={:d}'.format(int(max(0,verbose)))
   
   # ename = os.path.join('.',config['EXE'])
   
    cmd = ['mcrun']
    if mpi:
        cmd.append('--mpi={}'.format(mpi))
    cmd.append(config['INSTR']+'.instr')

    cmd += [sn, smode, sv, snpls]
    for key in kwargs:
        cmd += ['{}={}'.format(key, kwargs[key])]
    cmd += ['-d', respath]
    # clean output path if exists
    if os.path.exists(outname):
        shutil.rmtree(outname)
        
    # try to run it    
    out = None
    res = False
    try:
        cmd = ' '.join(cmd)
        print('Command: '+cmd)
        print('Running ... ',end='')
# for Python >= 3.7 :
#        out = subprocess.run(cmd, capture_output=True, text=True, shell=True, check=True)
# for Python < 3.7 :
        out = subprocess.run(cmd, cwd=config['WORKPATH'], 
                             stdout=subprocess.PIPE, stderr=subprocess.STDOUT, 
                             universal_newlines=True, shell=True, check=True,
                             timeout=timeout)
        out.check_returncode()
        print('done.')
        res = True
    except CalledProcessError as e:
        if verbose: print('failed.')
        msg = 'Can\'t execute {}.\n'.format(cmd)
        msg += 'Return code: {:d}\n'.format(e.returncode)
        if e.stderr: msg += 'stderr:\n'+e.stderr +'\n'
        if e.stdout: msg += 'stdout:\n'+e.stdout +'\n'
        print(msg)
        return res
    except TimeoutExpired as e:
        if verbose: print('timeout at {} s.'.format(e.timeout))
        return res
    except Exception:
        print('Error while executing {}'.format(cmd))
        traceback.print_exc(file=sys.stdout)
    if res and out.stdout:
        if not quiet: print(out.stdout)
        # save stdout in log file
        fout = os.path.join(outname,modeid+'.log')
        with open(fout, 'w') as f: 
            f.write(out.stdout)
            f.close()
        print('See results in "{}"\n'.format(outname))
    return res                            


def runModes(modes=[], counts=1e6, timeout=3600, **kwargs):
    
    """
    Run simulations for selected BEER reference modes.
    
    Parameters:
    -----------
    modes: list
        List of mode ID's
    counts: int
        Number of neutrons to trace.
    timeout: int
        Timeout in sec for one simulation
    
    Example:
    --------
    
    runModes(modes=['F1','PS1','MCA', 'IM0'])
    """

    # check configuration
    if not verifyConfig():
        return
    
    # check that the executable exists    
    exename = verifyInstrument()
    if not exename:
        return

    # DS1 must be run for the two wavelength frames separately
    if 'DS1' in modes:
        modes.remove('DS1')
        if not 'DS1_0' in modes:
            modes.extend(['DS1_0','DS1_-1'])
        if not 'DS1_-1' in modes:
            modes.extend(['DS1_0','DS1_-1'])
    res = (len(modes)>0)
    for m in modes:
        m = m.strip()
        sm = m.split('_')
        npls=0
        if (len(sm)>1):
            print(sm)
            print(''.join(sm[1:]))
            npls = int(''.join(sm[1:]))
        imode = BMOD.getModeIndex(sm[0])
        if (imode>=0):
            try:
                res = res and runSimulation(sm[0], n=counts, npulse=npls, 
                                  timeout=timeout, outdir=m, quiet=True, **kwargs)
            except Exception as e:
                print(e)
    return res 


#%% Process and plot results

def processResults(results, dataname='Lmon.dat', outfile='intensities.dat'):
    """
    Process a set of simulation results from McStas or SIMRES. 
    For each result, find given data file (dataname) and convert it 
    to the Data1D object. Print and (optionally) save the integral intensities 
    for all results as a table.    
    
    Each simulation result is saved in a separate directory, `results` is 
    a list of these directories (relative to `parentdir').
    
    `Example: results=['FC1', 'PSC1', 'MCA'], dataname='xmon.dat'` 
    
    would process all files 'xmon.dat' found in the subdirectories 
    'FC1', 'PS1' and 'MCA' relative to the workspace outpuut directory. 
    
    Parameters:
    -----------
    results: list of str
        list of directories (McStas) or file name bases (SIMRES) to search for
    dataname: str
        file name (McStas) or file name suffix (SIMRES) to search for
    outfile: str
        output file name
        
    """
    config = getConfig()
    if 'DS1' in results:
        results.remove('DS1')
        if not 'DS1_0' in results:
            results.extend(['DS1_0','DS1_-1'])
        if not 'DS1_-1' in results:
            results.extend(['DS1_0','DS1_-1'])

    datas = mcplot.processResults(results, 
                                  dataname=dataname, 
                                  parentdir=config['OUTPATH'],
                                  outfile=outfile,
                                  dformat='mcstas')
    return datas


def processRun(mode):
    """
    Process a single simulation results produced by McStas. 
    Find all specified files in given directory for given mode and convert them 
    to the `Data1D` objects. Return these objects as a list.
    
    The output file names are assumed to conform to this package, that is:
        
        `base/suffix.dat`
    
    where `base` is the directory name equal to the mode ID, 
    `suffix` denotes the monitor output file name, 
    for example `FC1/Lmon.dat` for wavelength distribution, mode=`FC1`.
        
    Parameters:
    -----------
    mode: str
        mode ID, one of those defined in beer.modes
    
    Returns:
    --------
    
    Retrieved results as Data1D objects.
        
    """
    
    config = getConfig()
    datas = mcplot.processRun(mode, 
                          files=getOutputFiles(), 
                          parentdir=config['OUTPATH'], 
                          dformat='mcstas')    
    return datas


def plotResults(datas, title='McStas', pdf=''):
    """
    Plot results retrieved by processResults(). 
    
    Parameters:
    -----------
    datas: 
        list of Data1D objects
    title: str
        Title to be shown on graph
    pdf: str
        File name to export (pdf format, without extension).
        Leave empty to suppress file export.
        
    """
    if pdf:
        config = getConfig()
        out = os.path.join(config['OUTPATH'],pdf)
    else:
        out = ''
    mcplot.plotDataSet(datas, title=title, pdf=out)


def verifyConfig(verbose=1):
    """
    Verify workspace configuration.
    """
    res = False
    try:
        config = getConfig()
        checkConfig(config)
        if verbose:
            print('Workspace directory: "{}"'.format(config['WORKPATH']))
            print('Simulation output directory: "{}"'.format(config['OUTPATH']))
            print('McStas instrument executable: {}'.format(config['EXE'])) 
        res = True
    except Exception as e:
        print(e)
    return res


def verifyInstrument(verbose=1):
    """
    Check that compiled instrument file exists.
    If successful, return path to the instrument executable.
    Otherwise returns empty string.
    """
    # check that the executable exists   
    res = ''
    config = getConfig()
    exename = os.path.join(config['WORKPATH'],config['EXE'])
    if not os.path.isfile(exename):
        if verbose:
            mcstas = getMcStas()
            scr = os.path.join(config['WORKPATH'],mcstas['cmd'])
            msg = 'Instrument executable not found, expected {}.\n'.format(exename)
            msg += 'Try to compile the instrument manually. See {}\n'.format(scr)
            print(msg)
    else:
        res = exename
    return res



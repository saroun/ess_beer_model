def plot1D(ax, dset, xscale=1, yscale=1, showvalue=True, grid=None):
    """Plot given data (class Data1D) on provided axis.
     
    Optionally, scale the x,y axes by provided factors (xscale, yscale).
    
    Parameters
    ----------
    ax: :class:`matplotlib.pyplot.Axes`
        Axis object to plot on.
    dset: list of :class:`~.Data1D`
        Data set to be plotted.
    xscale: float
        x-axis scaling
    yscale: float
        y-axis scaling
    showvalue: boolean
        Add intensity to the plot title (if dset has only one curve to plot).
    grid: dict
        If defined, contains arguments to be passed to the 
        :meth:`~matplotlib.pyplot.Axes.grid` method.
        
    """
    MEDIUM_SIZE = 10
    BIGGER_SIZE = 12 
    
    # table for special character replacement, PGPLOT -> LaTeX
    reptable = {'@@d(.*)@@u':'_{\\1}',
                '@@u':'^',
                '@@gl':'{@@lambda}',
                '@@gD':'{@@Delta}',
                '@@A':'{@@AA}',
                '@@m':'{@@mu}'
                }
                
    def replChar(s):
        """Convert special characters from PGPLOT to LaTeX math format."""
        if s.find('\\')>=0:
            # avoid problems with escape ...
            ss = re.sub(r'\\','@@',s)
            for c in reptable:
                ss = re.sub(c,reptable[c],ss)
                #if ss.find(c)>=0:
                    #ss = re.sub(c,reptable[c],ss)
            ss = re.sub('@@',r'\\',ss)
            out = '${}$'.format(ss)
        else:
            out = s
        return out
    
    def getx(d):
        """Consolidate x-label text."""
        xsc = xscale
        xlbl = d.xlabel
        q = xlbl.find('[\gms]')
        # convert microsec. to ms
        if q>0:
            xlbl = xlbl.replace('[\gms]','[ms]')
            xsc=0.001
        # convert other special characters to LaTeX math format
        xlbl = replChar(xlbl)
        # This works only for BEER_reference.instr with pre-defined output file names:
        # Is there another way how to find out that the horizontal monitor 
        # is actually used as vertical?
        q = d.fname.find('YMon.dat')
        if q>0:
            xlbl = xlbl.replace('x-Position','y-Position')    
        q = d.fname.find('VDivMon.dat')
        if q>0:
            xlbl = xlbl.replace('horizontal','vertical')              
        return [xlbl, xsc]
    
    if len(dset)<=0:
        return
    [xlbl, xsc] = getx(dset[0])
    # get y-limits
    ymax = 0
    for dd in dset:
        ymax =  max(ymax,np.max(dd.data[1])*yscale)
    ax.set_ylim(0, ymax*1.05) 
    if dset[0].xlimits is not None:
        ax.set_xlim(dset[0].xlimits[0]*xsc, dset[0].xlimits[1]*xsc)
    ax.set_xlabel(xlbl, fontsize=MEDIUM_SIZE)
    ax.set_ylabel(dset[0].ylabel, fontsize=MEDIUM_SIZE)
    ax.minorticks_on()
    ax.tick_params(axis='both', labelsize=MEDIUM_SIZE)
    if grid:
        ax.grid(**grid)
    title = dset[0].title
    # add intensity info if required and possible 
    if showvalue and (len(dset)==1) and dset[0].vals:
        sval = 'I = {:.3g}'.format(dset[0].vals['sum'])
        title += ' ; '+sval
        #ax.text(0.95, 0.95, sval, horizontalalignment='right',
        #        verticalalignment='top', transform=ax.transAxes)
    ax.set_title(title, fontsize=BIGGER_SIZE)
    for dd in dset:
        if len(dd.data)>2:
            ebar = np.multiply(dd.data[2],yscale)
        else:
            ebar=None
        ax.errorbar(np.multiply(dd.data[0],xsc), 
                    np.multiply(dd.data[1],yscale), 
                    yerr=ebar,
                    label=dd.legend)
    if dd.legend:
        ax.legend()


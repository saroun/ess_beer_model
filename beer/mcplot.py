class Data2D:
    """Data structure for 2D plot.
    
    Parameters
    ----------
    params: dict
        parameters for plotting
    dformat: str
        'mcstas' or 'simres', defines data format
    data: array-like
        2D pixel matrix
    scale: list
        matrix range as [[xmin, xmax],[ymin,ymax]]
    
    
    The recognized plot parameters are stored as:
    
    Attributes
    ----------
    xlabel: str
        X-axis label.
    ylabel: str
        Y-axis label.
    zlabel: str
        Value label.
    title:str
        Plot title, placed above the plot cell.
    comment: str
        Plot comment, not shown in the plot.
    vals: dict
        Sumary values retrieved from data, `sum` is used to show integral intensity. 
    
    """
    
    def __init__(self, params, dformat, data=None):
        if not (dformat=='simres'):
            msg = 'Only `simres` format is implemented for Data2D.\n'
            msg += 'McStas format will be added in next versions.'
            raise Exception(msg)
        self.title=''
        self.xlabel=''
        self.ylabel=''
        self.zlabel=''
        self.data=None
        self.scale=None
        self.fname=''
        self.comment=''
        self.dformat=dformat
        self.vals=None
        for key in params.keys():
            if (key=='xlabel'):
                self.xlabel=params['xlabel']
            elif (key=='ylabel'):
                self.ylabel=params['ylabel']
            elif (key=='zlabel'):
                self.zlabel=params['zlabel']
            elif (key=='title'):
                self.title=params['title']
            elif (key=='comment'):
                self.comment=params['comment']
            elif (key=='values'):
                self.vals = params['values'],
            elif (key=='scale'):
                self.scale = params['scale'] 
        if (data is not None):
            self.data=data
    
    def summary(self):
        """Return text sumarizing data properties."""
        out = 'Data file:\t{}\n'.format(self.fname)
        out += 'Title:\t{}\n'.format(self.title)
        if not self.data is None:
            out += 'Rows:\t{:d}\n'.format(self.data.shape[0])
            out += 'Columns:\t{:d}\n'.format(self.data.shape[1])
            out += 'Value range:\t{:g}, {:g}\n'.format(self.vals['zmin'], 
                                                     self.vals['zmax'])
            out += 'Centre:\t{:g}, {:g}\n'.format(self.vals['xmean'], 
                                                     self.vals['ymean'])
            out += 'FWHM:\t{:g}, {:g}\n'.format(self.vals['xwidth'], 
                                                     self.vals['ywidth'])
            
        if not self.scale is None:
            fmt = 'Scale:\tcols=({:g}, {:g}), rows=({:g}, {:g})\n'
            out += fmt.format(*self.scale[0], *self.scale[1])
        out += 'Intensity:\t{:g}\n'.format(self.vals['sum'])
        return out
    
    def calValues(self):
        """Calculate integral parameters: sum, centre, widths, zmin, zmax.
        
        Return as dict.
        """
        r8ln2 = np.sqrt(8*np.log(2))
        if self.data is None:
            return None
        nx = self.data.shape[0]
        ny = self.data.shape[1]       
        dx = (self.scale[0][1] - self.scale[0][0])/nx
        dy = (self.scale[1][1] - self.scale[1][0])/ny
        x = np.linspace(self.scale[0][0]+0.5*dx, self.scale[0][1]-0.5*dx, 
                        num=nx)
        y = np.linspace(self.scale[1][0]+0.5*dy, self.scale[1][1]-0.5*dy,
                        num=ny)      
        valx = np.sum(self.data, axis=0)
        valy = np.sum(self.data, axis=1)
        integ = np.sum(valx)
        
        
        sum0 = np.sum(valx)
        sum1 = valx.dot(x)
        sum2 = valx.dot(x**2)
        integ = sum0
        if sum0>0:
            meanx = sum1/sum0
            stdevx = np.sqrt(sum2/sum0 - meanx**2)
        else:
            meanx = 0.0
            stdevx = 0.0
        fwhmx = r8ln2*stdevx
        
        sum0 = np.sum(valy)
        sum1 = valy.dot(y)
        sum2 = valy.dot(y**2)
        if sum0>0:
            meany = sum1/sum0
            stdevy = np.sqrt(sum2/sum0 - meany**2)
        else:
            meany = 0.0
            stdevy = 0.0
        fwhmy = r8ln2*stdevy
        
        res = {'sum': integ,
               'xwidth': fwhmx,
               'ywidth': fwhmy,
               'xmean': meanx,
               'ymean': meany,
               'zmin' : np.min(self.data),
               'zmax' : np.max(self.data)
               }

        return res


class Data1D:
    """Data structure for 1D plot.
    
    Parameters
    ----------
    params: dict
        parameters for plotting
    dformat: str
        'mcstas' or 'simres', defines data format
    data: array-like
        data columns x, y, err (optional)
    
    
    The recognized plot parameters are stored as:
    
    Attributes
    ----------
    xlabel: str
        X-axis label.
    ylabel: str
        Y-axis label.
    title:str
        Plot title, placed above the plot cell.
    comment: str
        Plot comment, not shown in the plot.
    xlimits: list(2)
        X-axis limits. Actually not used, scale is automatic.
    vals: dict
        Data from the "Values" header, `sum` is used to show integral intensity. 
    legend: list of str
        Labels for individual data sets. If defined, they are used as the 
        value of the argument `legend` passed to :func:`errorbar`.
    
    """
    
    def __init__(self, params, dformat, data=None):
        self.title=''
        self.xlabel=''
        self.ylabel=''
        self.xlimits=None
        self.data=None
        self.legend=''
        self.fname=''
        self.comment=''
        self.dformat=dformat
        self.vals=None
        for key in params.keys():
            if (key=='xlabel'):
                self.xlabel=params['xlabel']
            elif (key=='ylabel'):
                self.ylabel=params['ylabel']  
            elif (key=='title'):
                self.title=params['title']
            elif (key=='comment'):
                self.comment=params['comment']
            elif (key=='xlimits'):
                self.xlimits=params['xlimits']
            elif (key=='values'):
                self.vals = params['values'] 
            elif (key=='legend'):
                self.legend = params['legend'] 
        if (data is not None):
            self.data=data
    
    def getParams(self):
        """Return parameters as dict."""
        params = {'xlabel':self.xlabel,
                  'ylabel':self.ylabel,
                  'title':self.title,
                  'comment':self.comment,
                  'xlimits':self.xlimits,
                  'values':self.vals,
                  'legend':self.legend}
        return params
    
    def summary(self):
        """Return text sumarizing data properties."""
        out = 'Data file:\t{}\n'.format(self.fname)
        out += 'Title:\t{}\n'.format(self.title)
        if self.data:
            out += 'Rows:\t{:d}\n'.format(len(self.data[0]))
        out += 'Intensity:\t{:g} +- {:g}\n'.format(self.vals['sum'], 
                                                   self.vals['e_sum'])
        return out
    
    def calValues(self):
        """Calculate integral parameters: intensity, spread, mean.
        
        Return as dict.
        """
        r8ln2 = np.sqrt(8*np.log(2))
        if not self.data:
            return None
        nc = len(self.data)
        x = np.array(self.data[0])
        y = np.array(self.data[1])
        if nc>2:
            err = np.array(self.data[2])
        else:
            err = None
        sum0 = np.sum(y)
        sum1 = y.dot(x)
        sum2 = y.dot(x**2)
        integ = sum0
        if sum0>0:
            mean = sum1/sum0
            stdev = np.sqrt(sum2/sum0 - mean**2)
        else:
            mean = 0.0
            stdev = 0.0
        fwhm = r8ln2*stdev
        res = {'sum': integ,
               'width': fwhm,
               'mean': mean}
        if (sum0>0) and (err is not None):
            res['e_sum'] = np.sqrt(np.sum(err**2))
            r = (x - mean)*err/sum0
            res['e_mean'] = np.sqrt(r.dot(r))
            r = (x-mean)**2 - stdev**2
            r = r*err/sum0
            res['e_width'] = r8ln2*np.sqrt(r.dot(r))/stdev
        return res


#%% Parsers of simulation results

"""
Define a key-valye pair for each item from headers. 
The key is used to search for given parameter in file headers. 
The values are used as keys in the resulting dict structure.
"""
# For McSTas
keysmc = {'values':'values',
          'xlabel':'xlabel',
          'ylabel':'ylabel',
          'xlimits':'xlimits',
          'title':'title'}

# For SIMRES:
# NOTE: intensity is calculated from the data, hence values=None.
keyssim = {'X-TITLE':'xlabel',
           'Y-TITLE':'ylabel',
           'LABEL(1)':'zlabel',
           'X-RANGE':'xlimits',
           'Y-RANGE':'ylimits',
           'scale (col,row)':'scale',
           'TITLE':'title',
           'COMMENT':'comment'
          }

       
def parseHdrMcStas(line):
    """Extract parameters from a single text line of a McStas format header.
    
    Parameter keys are defined as a list `keysmc`.
    
    Returns
    -------
    Hash map with found parameter keys and values.
    """
    res = {}
    if not line.startswith('#'):
        return res                  
    s =line[1:].replace(';',' ').strip()
    # get name, value pair (separated by the 1st :)
    inp = s.split(':')
    if (len(inp)<2):
        return res
    name = inp[0].strip()
    # skip if name is not in keys
    if not name in keysmc:
        return res
    # get a variable key, we already know it exists
    key = keysmc[name]
    # join all other parts separated by : if any
    if len(inp)>2:
        val = ':'.join(inp[1:])
    else:
        val = inp[1]
    # extract all strings in quotes into a list of strings
    if val.find('"')>=0:
        vals = re.findall(r'"(.*?)"', val)
    else:
        vals = [val.strip()]
    
    # now we need to to convert specific variables into valid data:
    # expect a pair of floats
    if name=='xlimits':
        s = vals[0].split()
        if len(s)>1:
            res[key] = [float(s[0]),float(s[1])]
    # expect 3 floats
    elif name=='values':
        s = vals[0].split()
        if len(s)>1:
            v = {}
            v['sum'] = float(s[0])
            v['e_sum'] = float(s[1])
            res[key] = v
    # expect a single string
    else:
        res[key] = ''.join(vals)              
    return res

           
def parseHdrSIMRES(ln):
    """Extract parameters from a single text line of a SIMRES format header.
    
    Parameter keys are defined as a list `keyssim`.
    
    Returns
    -------
    Hash map with found parameter keys and values.
    """
    res = {}
    if ln.find(':')<0:
        return res
    
    # get name, value pair (separated by the 1st :)
    inp = ln.strip().split(':')
    name = inp[0].strip()
    # skip if name is not in keys
    if not name in keyssim:
        return res
    # get a variable key, we already know it exists
    key = keyssim[name]
    # join all other parts separated by : if any
    if len(inp)>2:
        val = ':'.join(inp[1:])
    else:
        val = inp[1]
    # extract all strings in quotes into a list of strings
    if val.find('"')>=0:
        vals = re.findall(r'"(.*?)"', val)
    else:
        vals = [val.strip()]
    # now we need to to convert specific variables into valid data:
    # expect a pair of floats
    if key=='xlimits' or key=='ylimits':
        s = vals[0].split()
        if len(s)>1:
            res[key] = [float(s[0]),float(s[1])]
    elif key=='scale':
        s = vals[0].replace('(','').replace(')','').split(',')
        if len(s)==4:
            res[key] = [[float(s[0]),float(s[1])],[float(s[2]),float(s[3])]] 
        else:
            raise Exception('Wrong Data2D scale parameter format: '+vals[0])
    # expect a single string
    else:
        res[key] = ''.join(vals)
    return res
    

def parseFileMcStas(fname, yscale=1):
    """Load a data file and converts its content to a Data1D object.
     
    The input file must be a McStas 1-dim monitor output file.
    """
    params = {}
    x = []
    y = []
    err = []
    with open(fname, 'r') as f:
        lines = f.readlines()
        for L in lines:
            if (L.startswith('#')):
                p = parseHdrMcStas(L)
                if (len(p)>0):
                    params = {**params, **p}
            else:
                s = L.split()
                if (len(s)>2):
                    x += [float(s[0])]
                    y += [float(s[1])*yscale]
                    err += [float(s[2])*yscale]
        f.close()
    data = [x, y, err]
    out = Data1D(params, 'mcstas', data=data)
    out.vals = out.calValues()
    out.fname = fname
    return out


def parseFileSIMRES(fname, yscale=1, xcol=0, ycol=1, errcol=2):
    """Load a data file and converts its content to a Data1D object.
     
    The input file must be a SIMRES BEAM1D graph data file.
    """
    params = {}
    x = []
    y = []
    err = []
    sect = 0
    # assume 2 columns by default
    nc = -1
    ncmax = max(xcol, ycol)
    with open(fname, 'r') as f:
        lines = f.readlines()
        for L in lines:
            # start of the data section
            if L.strip().startswith('DATA_1D') or L.strip().startswith('SCAN_1D'):
                sect = 1
            # read header
            elif sect==0:
                p = parseHdrSIMRES(L)
                if (len(p)>0):
                    params = {**params, **p}
            # data section has 1 header line. 
            # get number of columns from here
            elif sect==1:
                s = shlex.split(L.strip())
                # s = L.strip().split()
                nc = len(s)
                sect = 2
            elif sect==2:
                s = L.split()
                if nc<0:
                    nc = len(s)
                if not len(s)==nc:
                    msg = 'Invalid data format, number of columns does not match header.'
                    raise Exception(msg)
                if nc < ncmax+1:
                    msg = 'Invalid data format, number of columns < {:d}'.format(ncmax)
                    raise Exception(msg)
                x += [float(s[xcol])]
                y += [float(s[ycol])*yscale]
                if nc >= errcol+1:
                    err += [float(s[errcol])*yscale]
        f.close()
    if nc >= errcol+1:
        data = [x, y, err]
    else:
        data = [x, y]
    out = Data1D(params, 'simres', data=data)
    out.vals = out.calValues()
    out.fname = fname
    return out



def parseFileSIMRES2D(fname, zscale=1):
    """Load a data file and converts its content to a Data2D object.
     
    The input file must be a SIMRES BEAM2D graph data file.
    """
    params = {}
    sect = 0
    # assume 2 columns by default
    nc = -1
    nr = -1
    rows = []
    with open(fname, 'r') as f:
        lines = f.readlines()
        for L in lines:
            # ignore empty lines and comments
            if len(L.strip())==0 or L.startswith('#'):
                pass
            else:
                # start of the data section
                if L.strip().startswith('DATA_2D') or L.strip().startswith('SCAN_2D'):
                    sect = 1
                # read header
                elif sect==0:
                    p = parseHdrSIMRES(L)
                    if (len(p)>0):
                        params = {**params, **p}
                # data section has no header line. 
                
                elif sect==1:
                    # 1st data row: get number of columns from here
                    if nr<0:
                        s = shlex.split(L.strip())
                        nc = len(s)
                    nr += 1
                    s = L.split()
                    if nc<0:
                        nc = len(s)
                    if not len(s)==nc:
                        msg = 'Invalid data format, variable number of columns.'
                        raise Exception(msg)
                    sa = np.array(s)
                    row = sa.astype(np.float)
                    rows.append(row)
        f.close()
    data = np.array(rows)
    out = Data2D(params, 'simres', data=data)
    out.vals = out.calValues()
    out.fname = fname
    return out

